// --------------------------------------------------------------------------
// Helper to normalize actors in the scene
// --------------------------------------------------------------------------
function normalizeActors(params: SceneBeatParams) {
  const { activeSquad, leadChar, antagonist } = params;
  const primaryChar = activeSquad[0] || leadChar;
  const secondaryChar = activeSquad[1] || (activeSquad[0]?.id !== leadChar.id ? leadChar : antagonist);

  return {
    sceneNumber: params.sceneNumber,
    totalScenes: params.totalScenes,
    progress: params.progress,
    actNumber: params.actNumber,
    primaryChar,
    secondaryChar,
    leadChar,
    antagonist,
    transition: params.transition,
    cleanTitleStr: params.cleanTitleStr,
    synopsis: params.synopsis,
  };
}
