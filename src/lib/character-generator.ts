import { CharacterBible, WorldCulture, VisualMedium } from './types';

/**
 * วิเคราะห์สเกลและจำนวนตัวละครที่เหมาะสมที่สุดจากพล็อตเรื่อง (Auto-Detect Story Character Scale)
 * - เรื่องมหากาพย์ / หอคอย 100 ชั้น / โจรสลัดลูกเรือ / สงครามกิลด์ -> 10 ตัวละคร (สไตล์วันพีช / ชาแนลดัง)
 * - ผจญภัย / ปาร์ตี้ฮันเตอร์ / ยอดฝีมือสำนักเซียน -> 8 ตัวละคร
 * - สืบสวน / ระทึกขวัญ / คู่หู -> 5 ตัวละคร
 */
export function detectStoryCharacterScale(
  title: string,
  synopsis: string,
  worldCulture?: string,
  subGenre?: string
): {
  count: number;
  label: string;
  reason: string;
} {
  const context = `${title} ${synopsis} ${worldCulture || ''} ${subGenre || ''}`.toLowerCase();

  // 1. Grand Ensemble: หอคอย 100 ชั้น, โจรสลัดลูกเรือวันพีช, สงครามมหากาพย์, กิลด์ใหญ่
  if (
    /หอคอย|100\s*ชั้น|ร้อยชั้น|ชั้นที่|tower|dungeon|solo|hunter|วันพีช|วันพีซ|โจรสลัด|ลูกเรือ|ล่าสมบัติ|pirate|crew|ลูฟี่|สงคราม|guild|ตระกูล/i.test(
      context
    )
  ) {
    return {
      count: 10,
      label: 'มหากาพย์ทีมใหญ่ (10 ตัวละคร)',
      reason: 'เหมาะสำหรับพล็อตหอคอย 100 ชั้น / กองเรือโจรสลัด / ปาร์ตี้เรดบอสครบทุกตำแหน่ง',
    };
  }

  // 2. Adventure / Cultivation / Tactical Squad: ผจญภัย, สำนักเซียน, หน่วยรบพิเศษ
  if (
    /ผจญภัย|ปาร์ตี้|ฮันเตอร์|เซียน|กำลังภายใน|ลมปราณ|สำนัก|กระบี่|หน่วยรบ|รบพิเศษ|ทหาร|ไซไฟ|หุ่นยนต์|adventure|squad|xianxia/i.test(
      context
    )
  ) {
    return {
      count: 8,
      label: 'ทีมยอดฝีมือ (8 ตัวละคร)',
      reason: 'เหมาะสำหรับทีมผจญภัย / ยอดฝีมือสำนักเซียน / หน่วยรบยุทธวิธีครบทีม',
    };
  }

  // 3. Mystery / Thriller / Cyberpunk / Detective
  if (/สืบสวน|ฆาตกรรม|ระทึกขวัญ|สายลับ|ไขคดี|mystery|thriller|detective/i.test(context)) {
    return {
      count: 5,
      label: 'แกนนำสืบสวน (5 ตัวละคร)',
      reason: 'เหมาะสำหรับแนวสืบสวน ระทึกขวัญ ชิงไหวชิงพริบ',
    };
  }

  // Default: มาตรฐาน 8 ตัวละคร
  return {
    count: 8,
    label: 'ทีมภาพยนตร์มาตรฐาน (8 ตัวละคร)',
    reason: 'จัดโครงสร้างตัวละครครบถ้วน: ผู้นำ, มือขวา, เสนาธิการ, ซัพพอร์ต, และบอสใหญ่',
  };
}

